    let currentSlideIdx = 0;
    let modalSlideshowInterval = null;

    function openProjectModal(idx) {
        const p = projectsData[idx];
        const modal = document.getElementById('projectModal');
        if (!modal) return;

        document.getElementById('modalTitle').textContent = p.project_name;
        document.getElementById('modalDesc').textContent = p.project_description;
        
        // Show ALL tech tags in modal
        const allTagsHTML = p.tech_stack.map(tag => {
            const tagClass = getTagClass(tag);
            return `<span class="project-tag ${tagClass}">${tag}</span>`;
        }).join('\n');
        document.getElementById('modalTags').innerHTML = allTagsHTML;

        // Populate links
        document.getElementById('modalLinks').innerHTML = getLinksHTML(p);

        // Load media (combining video and images)
        const images = p.images || ["assets/images/cert-placeholder.png"];
        const slidesContainer = document.getElementById('modalSlides');
        slidesContainer.innerHTML = '';
        
        const slidesMedia = [];
        if (p.video) {
            slidesMedia.push({ type: 'video', url: p.video });
        }
        images.forEach(imgUrl => {
            slidesMedia.push({ type: 'image', url: imgUrl });
        });

        slidesMedia.forEach((media, i) => {
            if (media.type === 'video') {
                const video = document.createElement('video');
                video.className = `project-slide-img ${i === 0 ? 'active' : ''}`;
                video.src = media.url;
                video.autoplay = true;
                video.muted = true;
                video.loop = true;
                video.playsInline = true;
                video.controls = true;
                slidesContainer.appendChild(video);
            } else {
                const img = document.createElement('img');
                img.className = `project-slide-img ${i === 0 ? 'active' : ''}`;
                img.src = media.url;
                img.alt = p.project_name;
                slidesContainer.appendChild(img);
            }
        });

        // Load dots
        const dotsContainer = document.getElementById('modalDots');
        dotsContainer.innerHTML = '';
        slidesMedia.forEach((_, i) => {
            const dot = document.createElement('span');
            dot.className = `project-slider-dot ${i === 0 ? 'active' : ''}`;
            dot.addEventListener('click', (e) => {
                e.stopPropagation();
                playSfx('hover');
                showSlide(i);
            });
            dotsContainer.appendChild(dot);
        });

        currentSlideIdx = 0;

        // Arrows setup
        const prevBtn = document.getElementById('modalPrev');
        const nextBtn = document.getElementById('modalNext');
        if (slidesMedia.length > 1) {
            prevBtn.style.display = 'flex';
            nextBtn.style.display = 'flex';
            
            // Set auto slideshow cycle
            if (modalSlideshowInterval) clearInterval(modalSlideshowInterval);
            modalSlideshowInterval = setInterval(() => {
                // Pause rotation if current slide is a video so user can watch it
                const slides = slidesContainer.querySelectorAll('.project-slide-img');
                const currentSlide = slides[currentSlideIdx];
                if (currentSlide && currentSlide.tagName === 'VIDEO') {
                    return;
                }
                showSlide(currentSlideIdx + 1);
            }, 3500);
        } else {
            prevBtn.style.display = 'none';
            nextBtn.style.display = 'none';
            if (modalSlideshowInterval) clearInterval(modalSlideshowInterval);
        }

        // Setup Arrow Actions
        prevBtn.onclick = (e) => {
            e.stopPropagation();
            playSfx('hover');
            resetAutoplay();
            showSlide(currentSlideIdx - 1);
        };
        nextBtn.onclick = (e) => {
            e.stopPropagation();
            playSfx('hover');
            resetAutoplay();
            showSlide(currentSlideIdx + 1);
        };

        function resetAutoplay() {
            if (modalSlideshowInterval) {
                clearInterval(modalSlideshowInterval);
                modalSlideshowInterval = setInterval(() => {
                    showSlide(currentSlideIdx + 1);
                }, 3500);
            }
        }

        modal.classList.add('active');
        document.body.style.overflow = 'hidden'; // Lock background scrolling
    }

    function showSlide(index) {
        const slidesContainer = document.getElementById('modalSlides');
        const dotsContainer = document.getElementById('modalDots');
        if (!slidesContainer) return;

        const slides = slidesContainer.querySelectorAll('.project-slide-img');
        const dots = dotsContainer.querySelectorAll('.project-slider-dot');
        if (slides.length <= 1) return;

        let targetIndex = index;
        if (targetIndex >= slides.length) targetIndex = 0;
        if (targetIndex < 0) targetIndex = slides.length - 1;

        // Pause current video slide when switching away
        const currentSlide = slides[currentSlideIdx];
        if (currentSlide && currentSlide.tagName === 'VIDEO') {
            currentSlide.pause();
        }

        slides[currentSlideIdx].classList.remove('active');
        dots[currentSlideIdx].classList.remove('active');

        slides[targetIndex].classList.add('active');
        dots[targetIndex].classList.add('active');

        // Play target video slide when switching to it
        const targetSlide = slides[targetIndex];
        if (targetSlide && targetSlide.tagName === 'VIDEO') {
            targetSlide.currentTime = 0;
            targetSlide.play().catch(err => console.log("Video auto-play failed in modal slider:", err));
        }

        currentSlideIdx = targetIndex;
    }

